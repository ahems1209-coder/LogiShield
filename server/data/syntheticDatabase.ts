// Helper to calculate days remaining and reorder point
export function calcDaysRemaining(stock: number, predDaily: number): number {
  if (predDaily <= 0) return 999;
  return Number((stock / predDaily).toFixed(1));
}

export function calcReorderPoint(leadDays: number, predDaily: number, safety: number): number {
  return Math.round((leadDays * predDaily) + safety);
}

